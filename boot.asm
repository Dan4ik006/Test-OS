use16
org 0x7C00

bios_start:
  cli
  xor ax, ax
  mov es, ax
  mov ds, ax
  mov ss, ax
  mov esp, 0x7C00
  sti

  ; 1. Загружаем setup.asm (2 сектора, адрес 0x4000)
  mov bx, 0x4000
  mov ax, 0x0202        ; AH=02 (читать), AL=2 сектора
  mov cx, 0x0002        ; Цилиндр 0, Сектор 2
  xor dx, dx            ; Головка 0, Дисковод 0
  int 0x13
  jc .error

  ; 2. Загружаем GDT.asm (1 сектор, адрес 0x5000)
  mov bx, 0x5000
  mov ax, 0x0201        ; AL=1 сектор
  mov cx, 0x0004        ; Сектор 4
  xor dx, dx
  int 0x13
  jc .error

  ; 3. Загружаем IDT.asm (4 сектора, адрес 0x2000)
  mov bx, 0x2000
  mov ax, 0x0204        ; AL=4 сектора
  mov cx, 0x0005        ; Сектор 5
  xor dx, dx
  int 0x13
  jc .error

  ; 4. ЗАГРУЖАЕМ ЯДРО И КАРТИНКУ (Читаем 20 секторов, начиная с 9-го)
  ; Делим чтение на две части, чтобы BIOS старого VirtualBox не сходил с ума 
  ; от выхода за пределы стандартной дорожки (18 секторов).
  
  ; Часть 4.1: Дочитываем остаток первой дорожки (10 секторов: с 9 по 18)
  mov bx, 0x8000
  mov ax, 0x020A        ; AL = 10 секторов
  mov cx, 0x0009        ; Цилиндр 0, Сектор 9
  xor dx, dx            ; Головка 0
  int 0x13
  jc .error

  ; Часть 4.2: Читаем продолжение ядра со следующей стороны дискеты (еще 10 секторов)
  ; Сдвигаем буфер в памяти вперед: 0x8000 + (10 секторов * 512 байт) = 0x9400
  mov bx, 0x9400
  mov ax, 0x020A        ; AL = 10 секторов
  mov cx, 0x0001        ; Цилиндр 0, Сектор 1 (начинаем сначала дорожки)
  mov dx, 0x0100        ; DH = 1 (ПЕРЕКЛЮЧАЕМ НА ГОЛОВКУ 1), DL = 0
  int 0x13
  jc .error

  ; Все загрузилось без ошибок, прыгаем в setup
  jmp 0x4000

.error:
  ; Если упали тут — экран останется черным, но мы хотя бы поймем, что дело в диске
  mov ax, 0x0E45 ; Буква 'E'
  xor bx, bx
  int 0x10
  jmp $

TIMES 510-($-$$) db 0
dw 0xAA55

include "setup.asm"
include "GDT.asm"
include "IDT.asm"
include "kernel.asm"
